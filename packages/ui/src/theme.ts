import { theme as antdTheme, type ThemeConfig } from 'antd'
import { fonts, paletteFor, type ThemeMode } from '@projectos/design-tokens'

export function createAntdTheme(mode: ThemeMode): ThemeConfig {
  const palette = paletteFor(mode)
  const isDark = mode === 'dark'
  return {
    algorithm: isDark ? antdTheme.darkAlgorithm : antdTheme.defaultAlgorithm,
    cssVar: { key: 'projectos' },
    hashed: false,
    token: {
      colorPrimary: palette.accent,
      colorInfo: palette.info,
      colorSuccess: palette.success,
      colorWarning: palette.warning,
      colorError: palette.danger,
      colorBgBase: palette.canvas,
      colorBgLayout: palette.canvas,
      colorBgContainer: palette.surface,
      colorBgElevated: palette.surfaceRaised,
      colorFillAlter: palette.surfaceSunken,
      colorFillSecondary: palette.surfaceHover,
      colorFillTertiary: palette.surfaceHover,
      colorFillQuaternary: palette.surfaceSunken,
      colorText: palette.textPrimary,
      colorTextSecondary: palette.textSecondary,
      colorTextTertiary: palette.textTertiary,
      colorTextQuaternary: palette.textDisabled,
      colorBorder: palette.border,
      colorBorderSecondary: palette.divider,
      colorSplit: palette.divider,
      colorLink: palette.accent,
      colorLinkHover: palette.accentStrong,
      colorWhite: palette.textInverse,
      fontFamily: `"SF Pro Display", "SF Pro Text", Inter, ${fonts.sans}`,
      fontFamilyCode: fonts.mono,
      fontSize: 14,
      fontSizeSM: 13,
      fontSizeLG: 15,
      fontSizeXL: 16,
      fontSizeHeading1: 28,
      fontSizeHeading2: 22,
      fontSizeHeading3: 18,
      fontSizeHeading4: 16,
      fontSizeHeading5: 14,
      lineHeight: 1.55,
      controlHeight: 36,
      controlHeightSM: 28,
      controlHeightLG: 40,
      borderRadius: 12,
      borderRadiusSM: 9,
      borderRadiusLG: 20,
      borderRadiusXS: 6,
      wireframe: false,
      boxShadow: '0 10px 30px -16px rgba(15,26,45,.20), 0 2px 6px rgba(15,26,45,.05)',
      boxShadowSecondary: '0 24px 60px -28px rgba(15,26,45,.30), 0 6px 18px -10px rgba(15,26,45,.14)',
      boxShadowTertiary: '0 1px 3px rgba(15,26,45,.06)',
      motionDurationFast: '0.16s',
      motionDurationMid: '0.26s',
      motionDurationSlow: '0.4s',
    },
    components: {
      Button: {
        primaryShadow: 'none',
        defaultShadow: 'none',
        dangerShadow: 'none',
        fontWeight: 500,
        borderRadius: 11,
        borderRadiusLG: 13,
        defaultBorderColor: palette.border,
        defaultColor: palette.textPrimary,
        defaultBg: palette.surface,
        defaultHoverBg: palette.surfaceHover,
      },
      Input: {
        activeShadow: `0 0 0 3px ${palette.focusRing}`,
        hoverBorderColor: palette.borderStrong,
        activeBorderColor: palette.accent,
        colorBgContainer: isDark ? palette.surfaceSunken : palette.surface,
      },
      Select: {
        optionSelectedBg: palette.accentSoft,
        optionSelectedColor: palette.accent,
        optionActiveBg: palette.surfaceHover,
        colorBgContainer: isDark ? palette.surfaceSunken : palette.surface,
      },
      InputNumber: {
        activeShadow: `0 0 0 3px ${palette.focusRing}`,
      },
      Card: {
        borderRadiusLG: 16,
        colorBorderSecondary: palette.divider,
        headerBg: 'transparent',
        bodyPadding: 20,
        headerHeight: 52,
      },
      Modal: {
        contentBg: palette.surfaceRaised,
        headerBg: 'transparent',
        titleFontSize: 18,
        borderRadiusLG: 20,
        paddingContentHorizontalLG: 24,
      },
      Drawer: {
        colorBgElevated: palette.surfaceRaised,
        paddingLG: 20,
      },
      Menu: {
        itemBg: 'transparent',
        subMenuItemBg: 'transparent',
        itemSelectedBg: palette.accentSoft,
        itemSelectedColor: palette.accent,
        itemColor: palette.textSecondary,
        itemHoverBg: palette.surfaceHover,
        itemHoverColor: palette.textPrimary,
        itemActiveBg: palette.surfaceSunken,
        itemBorderRadius: 9,
        itemHeight: 38,
        itemMarginInline: 6,
        itemMarginBlock: 2,
        iconSize: 16,
        activeBarWidth: 0,
        activeBarBorderWidth: 0,
        collapsedIconSize: 17,
      },
      Table: {
        headerBg: palette.surfaceSunken,
        headerColor: palette.textSecondary,
        headerSplitColor: 'transparent',
        headerBorderRadius: 12,
        borderColor: palette.divider,
        rowHoverBg: palette.surfaceHover,
        rowSelectedBg: palette.accentSoft,
        rowSelectedHoverBg: palette.accentSoft,
        cellPaddingBlock: 11,
        cellPaddingInline: 14,
        fontSize: 12.5,
      },
      Tabs: {
        itemColor: palette.textSecondary,
        itemSelectedColor: palette.textPrimary,
        itemHoverColor: palette.textPrimary,
        inkBarColor: palette.accent,
        titleFontSize: 13,
        horizontalItemGutter: 24,
        horizontalItemPadding: '10px 0',
      },
      Segmented: {
        trackBg: palette.surfaceSunken,
        itemColor: palette.textSecondary,
        itemSelectedBg: palette.surface,
        itemSelectedColor: palette.textPrimary,
        itemHoverBg: palette.surfaceHover,
        trackPadding: 3,
        borderRadius: 9,
        borderRadiusSM: 7,
      },
      Tag: {
        defaultBg: palette.surfaceSunken,
        defaultColor: palette.textSecondary,
        borderRadiusSM: 6,
        fontSizeSM: 11,
        lineHeightSM: 1.6,
      },
      Tooltip: {
        colorBgSpotlight: isDark ? palette.surfaceRaised : '#1E2430',
        colorTextLightSolid: '#F7F9FC',
        borderRadius: 8,
        fontSize: 12,
      },
      Dropdown: {
        borderRadiusLG: 12,
        paddingBlock: 6,
      },
      Popover: {
        borderRadiusLG: 14,
        colorBgElevated: palette.surfaceRaised,
      },
      Progress: {
        defaultColor: palette.accent,
        remainingColor: palette.surfaceSunken,
        circleTextColor: palette.textPrimary,
      },
      Timeline: {
        dotBg: palette.surface,
        tailColor: palette.border,
      },
      Divider: {
        colorSplit: palette.divider,
      },
      Avatar: {
        colorTextPlaceholder: palette.textTertiary,
      },
      Badge: {
        colorError: palette.danger,
        colorSuccess: palette.success,
        colorWarning: palette.warning,
      },
      Alert: {
        borderRadiusLG: 12,
      },
      Empty: {
        colorTextDescription: palette.textTertiary,
      },
      Notification: {
        colorBgElevated: palette.surfaceRaised,
        borderRadiusLG: 14,
      },
    },
  }
}
